-- Editor- and toolchain-facing hints written next to a generated project.
--
-- Why this exists: a fresh C/C++ project has no compile_commands.json until
-- the first build, so clangd used to guess (default flags, wrong include dirs,
-- and .h files parsed as C). These files make the standard and include paths
-- explicit from the very first :edit.

local M = {}

--- `compile_flags.txt`: clangd's fallback database, used until the real
--- `compile_commands.json` exists. Relative paths are resolved from the
--- directory containing the file (the project root), not from the source file.
---@param standard string e.g. "c++23" or "c23"
---@param includes? string[] directories relative to the project root
---@return string
function M.compile_flags(standard, includes)
  local lines = {
    "-std=" .. standard,
    "-Wall",
    "-Wextra",
  }
  for _, dir in ipairs(includes or {}) do
    lines[#lines + 1] = "-I" .. dir
  end
  return table.concat(lines, "\n") .. "\n"
end

--- `.clangd`: clangd picks the language from the extension and assumes C++ for
--- `.h`, which breaks C projects (and C++ headers need header mode). Force the
--- header language explicitly.
---@param standard string e.g. "c++23"
---@param mode? string "c++-header" (default) or "c-header"
---@return string
function M.clangd(standard, mode)
  return table.concat({
    "# Generated by Scaffold.nvim.",
    "# Flags come from compile_flags.txt before the first build and from",
    "# build/compile_commands.json afterwards.",
    "---",
    "If:",
    "  PathMatch: " .. [[.*\.(h|hh|hpp|hxx)$]],
    "CompileFlags:",
    "  Add:",
    "    - -x" .. (mode or "c++-header"),
    "    - -std=" .. standard,
    "",
  }, "\n")
end

return M
