-- C project templates.

local editor = require("scaffold.templates.editor")
local standards = require("scaffold.templates.standards")

local function cmake_lists(ctx)
  local standard = ctx.standard or "17"
  return table.concat({
    "cmake_minimum_required(VERSION 3.20)",
    ("project(%s VERSION 0.1.0 LANGUAGES C)"):format(ctx.project_slug),
    "",
    ("set(CMAKE_C_STANDARD %s)"):format(standard),
    "set(CMAKE_C_STANDARD_REQUIRED ON)",
    "set(CMAKE_C_EXTENSIONS OFF)",
    "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)",
    "",
    ("add_executable(%s src/main.c)"):format(ctx.project_slug),
    "",
    "include(CTest)",
    "if(BUILD_TESTING)",
    ("  add_test(NAME %s-smoke COMMAND %s)"):format(ctx.project_slug, ctx.project_slug),
    "endif()",
    "",
  }, "\n")
end

local function main_c()
  return table.concat({
    "#include <stdio.h>",
    "",
    "int main(void) {",
    '    printf("Hello from {{project_name}}!\\n");',
    "    return 0;",
    "}",
    "",
  }, "\n")
end

local c_cmake = {
  id = "c-cmake",
  name = "C CMake Project",
  language = "c",
  version = 1,
  description = "A C console application built with CMake.",
  validate_options = standards.check,
  build_systems = { "cmake" },
  runtime_options = { "gcc", "clang" },
  default_runtime = "gcc",
  default_build_system = "cmake",
  requires = { "cmake" },
  options = {
    standard = {
      type = "select",
      label = "C standard",
      values = { "11", "17", "23" },
      default = "17",
    },
  },
  files = {
    ["CMakeLists.txt"] = cmake_lists,
    ["src/main.c"] = main_c,
    [".gitignore"] = table.concat({
      "/build/",
      "*.o",
      "compile_commands.json",
      "",
    }, "\n"),
    -- Editor hints: clangd gets the C standard before the first configure, and
    -- .h files must be parsed as C (clangd assumes C++ for headers).
    ["compile_flags.txt"] = function(ctx)
      return editor.compile_flags("c" .. (ctx.standard or "17"))
    end,
    [".clangd"] = function(ctx)
      return editor.clangd("c" .. (ctx.standard or "17"), "c-header")
    end,
    ["README.md"] = table.concat({
      "# {{project_name}}",
      "",
      "C project generated by Scaffold.nvim (C{{standard}}, CMake).",
      "",
      "```sh",
      "cmake -S . -B build",
      "cmake --build build",
      "./build/{{project_slug}}",
      "```",
      "",
    }, "\n"),
  },
  commands = {
    configure = { "cmake", "-S", ".", "-B", "build", "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON" },
    build = { "cmake", "--build", "build" },
    test = { "ctest", "--test-dir", "build", "--output-on-failure" },
    run = function(ctx)
      return { "./build/" .. ctx.project_slug }
    end,
    clean = { "cmake", "--build", "build", "--target", "clean" },
  },
  install_commands = {},
}

local function makefile(ctx)
  return table.concat({
    "CC ?= gcc",
    ("CFLAGS ?= -std=c%s -Wall -Wextra -O2"):format(ctx.standard or "17"),
    "",
    "TARGET := {{project_slug}}",
    "",
    ".PHONY: all run test clean",
    "",
    "all: $(TARGET)",
    "",
    "$(TARGET): src/main.c",
    "\t$(CC) $(CFLAGS) -o $@ $<",
    "",
    "run: $(TARGET)",
    "\t./$(TARGET)",
    "",
    "test: $(TARGET)",
    "\t./$(TARGET)",
    "",
    "clean:",
    "\trm -f $(TARGET)",
    "",
  }, "\n")
end

