      "make test",
      "make clean",
      "```",
      "",
    }, "\n"),
  },
  commands = {
    build = { "make" },
    run = { "make", "run" },
    test = { "make", "test" },
    clean = { "make", "clean" },
  },
  install_commands = {},
}

return { templates = { c_cmake, c_make } }
