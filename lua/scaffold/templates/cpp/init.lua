-- C++ project templates.

local editor = require("scaffold.templates.editor")
local standards = require("scaffold.templates.standards")

local function cmake_lists(ctx)
  local standard = ctx.standard or "23"
  local head = table.concat({
    "cmake_minimum_required(VERSION 3.20)",
    ("project(%s VERSION 0.1.0 LANGUAGES CXX)"):format(ctx.project_slug),
    "",
    ("set(CMAKE_CXX_STANDARD %s)"):format(standard),
    "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
    "set(CMAKE_CXX_EXTENSIONS OFF)",
    "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)",
    "",
  }, "\n")

  if ctx.kind == "library" then
    return head .. table.concat({
      ("add_library(%s src/lib.cpp)"):format(ctx.project_slug),
      ("target_include_directories(%s PUBLIC ${CMAKE_CURRENT_SOURCE_DIR}/include)"):format(ctx.project_slug),
      "",
    }, "\n")
  end

  return head .. table.concat({
    ("add_executable(%s src/main.cpp)"):format(ctx.project_slug),
    "",
    "include(CTest)",
    "if(BUILD_TESTING)",
    ("  add_test(NAME %s-smoke COMMAND %s)"):format(ctx.project_slug, ctx.project_slug),
    "endif()",
    "",
  }, "\n")
end

local function main_cpp()
  return table.concat({
    "#include <iostream>",
    "",
    "int main() {",
    '    std::cout << "Hello from {{project_name}}!" << std::endl;',
    "    return 0;",
    "}",
    "",
  }, "\n")
end

local function lib_hpp(ctx)
  return table.concat({
    "#pragma once",
    "",
    "#include <string>",
    "",
    "namespace {{project_module}} {",
    "",
    'std::string greet(const std::string &name = "world");',
    "",
    "} // namespace {{project_module}}",
    "",
  }, "\n")
end

local function lib_cpp(ctx)
  return table.concat({
    'src/lib.cpp is generated below; this placeholder is replaced by the file map.',
  }, "\n")
end

local cpp_cmake = {
  id = "cpp-cmake",
  name = "C++ CMake Project",
  language = "cpp",
  version = 1,
  description = "A C++ console application or library built with CMake.",
  validate_options = standards.check,
  build_systems = { "cmake" },
  runtime_options = { "g++", "clang++" },
  default_runtime = "g++",
  default_build_system = "cmake",
  requires = { "cmake" },
  options = {
    standard = {
      type = "select",
      label = "C++ standard",
      values = { "17", "20", "23", "26" },
      default = "23",
    },
    kind = {
      type = "select",
      label = "Project kind",
      values = { "console", "library" },
      default = "console",
    },
  },
  files = {
    ["CMakeLists.txt"] = cmake_lists,
    ["src/main.cpp"] = function(ctx)
      if ctx.kind == "library" then
        return nil
      end
      return main_cpp()
    end,
    ["src/lib.cpp"] = function(ctx)
      if ctx.kind ~= "library" then
        return nil
      end
      return table.concat({
        '#include "{{project_slug}}/lib.hpp"',
        "",
        "namespace {{project_module}} {",
        "",
        'std::string greet(const std::string &name) {',
        '    return "Hello, " + name + "!";',
        "}",
        "",
        "} // namespace {{project_module}}",
        "",
      }, "\n")
    end,
    ["include/{{project_slug}}/lib.hpp"] = function(ctx)
      if ctx.kind ~= "library" then
        return nil
      end
      return lib_hpp(ctx)
    end,
    [".gitignore"] = table.concat({
      "/build/",
      "/.cache/",
      "*.o",
      "*.obj",
      "compile_commands.json",
      "",
    }, "\n"),
    -- Editor hints: without these clangd guesses flags and treats .h as C
    -- before the first CMake configure produces compile_commands.json.
    ["compile_flags.txt"] = function(ctx)
      local includes = ctx.kind == "library" and { "include" } or {}
      return editor.compile_flags("c++" .. (ctx.standard or "23"), includes)
    end,
    [".clangd"] = function(ctx)
      return editor.clangd("c++" .. (ctx.standard or "23"))
    end,
    ["README.md"] = table.concat({
      "# {{project_name}}",
      "",
      "C++ project generated by Scaffold.nvim (C++{{standard}}, CMake).",
      "",
      "## Build",
      "",
      "```sh",
      "cmake -S . -B build",
      "cmake --build build",
      "```",
      "",
      "## Run",
      "",
      "```sh",
      "./build/{{project_slug}}",
      "```",
      "",
    }, "\n"),
  },
  commands = {
    configure = { "cmake", "-S", ".", "-B", "build", "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON" },
    build = { "cmake", "--build", "build" },
    test = function(ctx)
      if ctx.kind == "library" then
        return nil
      end
      return { "ctest", "--test-dir", "build", "--output-on-failure" }
    end,
    run = function(ctx)
      if ctx.kind == "library" then
        return nil
      end
      return { "./build/" .. ctx.project_slug }
    end,
    clean = { "cmake", "--build", "build", "--target", "clean" },
  },
  install_commands = {},
}

local function makefile(ctx)
  return table.concat({
    "CXX ?= g++",
    ("CXXFLAGS ?= -std=c++%s -Wall -Wextra -O2"):format(ctx.standard or "23"),
    "",
    "TARGET := {{project_slug}}",
    "",
    ".PHONY: all run test clean",
    "",
    "all: $(TARGET)",
    "",
    "$(TARGET): src/main.cpp",
    "\t$(CXX) $(CXXFLAGS) -o $@ $<",
    "",
    "run: $(TARGET)",
    "\t./$(TARGET)",
    "",
    "test: $(TARGET)",
    "\t./$(TARGET)",
    "",
    "clean:",
    "\trm -f $(TARGET)",
    "",
  }, "\n")
end

local cpp_make = {
  id = "cpp-make",
  name = "C++ Makefile Project",
  language = "cpp",
  version = 1,
  description = "A small C++ console application built with Make.",
  validate_options = standards.check,
  build_systems = { "make" },
  runtime_options = { "g++", "clang++" },
  default_runtime = "g++",
  default_build_system = "make",
  requires = { "make" },
  options = {
    standard = {
      type = "select",
      label = "C++ standard",
      values = { "17", "20", "23", "26" },
      default = "23",
    },
  },
  files = {
    ["Makefile"] = makefile,
    ["src/main.cpp"] = main_cpp,
    [".gitignore"] = "{{project_slug}}\n*.o\ncompile_commands.json\n",
    ["compile_flags.txt"] = function(ctx)
      return editor.compile_flags("c++" .. (ctx.standard or "23"))
    end,
    [".clangd"] = function(ctx)
      return editor.clangd("c++" .. (ctx.standard or "23"))
    end,
    ["README.md"] = table.concat({
      "# {{project_name}}",
      "",
      "C++ project generated by Scaffold.nvim (Make).",
      "",
      "```sh",
      "make",
      "make run",
      "make test",
      "make clean",
      "```",
      "",
    }, "\n"),
  },
  commands = {
    build = { "make" },
    run = { "make", "run" },
    test = { "make", "test" },
    clean = { "make", "clean" },
  },
  install_commands = {},
}

return { templates = { cpp_cmake, cpp_make } }
