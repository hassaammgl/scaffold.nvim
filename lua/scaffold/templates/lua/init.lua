-- Lua templates: a plain CLI script and a Neovim plugin skeleton.

local function lua_module_plain(ctx)
  return table.concat({
    ("-- %s module."):format(ctx.project_name),
    "",
    "local M = {}",
    "",
    "---@param name? string",
    "---@return string",
    "function M.greet(name)",
    '  return ("Hello, %s!"):format(name or "world")',
    "end",
    "",
    "return M",
    "",
  }, "\n")
end

local function lua_main(ctx)
  return table.concat({
    ("local greet = require(\"%s\").greet"):format(ctx.project_slug),
    "",
    'print(greet(arg and arg[1] or "world"))',
    "",
  }, "\n")
end

local function lua_tests_cli(ctx)
  return table.concat({
    "-- Zero-dependency test runner: lua tests/run.lua",
    ("local plugin = require(\"%s\")"):format(ctx.project_slug),
    "",
    "local failures, count = 0, 0",
    "",
    "local function test(name, fn)",
    "  count = count + 1",
    "  local ok, err = pcall(fn)",
    "  if ok then",
    '    print("ok   " .. name)',
    "  else",
    "    failures = failures + 1",
    '    print("FAIL " .. name .. ": " .. tostring(err))',
    "  end",
    "end",
    "",
    "local function eq(actual, expected)",
    "  if actual ~= expected then",
    "    error(('expected %q, got %q'):format(expected, actual), 2)",
    "  end",
    "end",
    "",
    'test("greet defaults to world", function()',
    '  eq(plugin.greet(), "Hello, world!")',
    "end)",
    "",
    'test("greet uses the given name", function()',
    '  eq(plugin.greet("scaffold"), "Hello, scaffold!")',
    "end)",
    "",
    "print(('%d/%d passed'):format(count - failures, count))",
    "os.exit(failures == 0 and 0 or 1)",
    "",
  }, "\n")
end

local function lua_makefile(ctx)
  return table.concat({
    "LUA ?= lua",
    "",
    ".PHONY: run test check clean",
    "",
    "run:",
    "\t$(LUA) main.lua",
    "",
    "test:",
    "\t$(LUA) tests/run.lua",
    "",
    "check:",
    ("\t$(LUA) -e 'assert(loadfile(\"%s.lua\")); assert(loadfile(\"main.lua\")); print(\"syntax ok\")'"):format(
      ctx.project_slug
    ),
    "",
    "clean:",
    "\trm -f luac.out",
    "",
  }, "\n")
end

local function lua_readme(ctx)
  return table.concat({
    "# {{project_name}}",
    "",
    "Lua project generated by Scaffold.nvim.",
    "",
    "```sh",
    "make run     # lua main.lua",
    "make test    # lua tests/run.lua (no dependencies)",
    "make check   # syntax check",
    "```",
    "",
    "Optional tooling: `luarocks install busted luacheck`, `pacman -S stylua`.",
    "",
  }, "\n")
end

local function nvim_plugin_module(ctx)
  return table.concat({
    ("-- %s: public API."):format(ctx.project_name),
    "",
    "local M = {}",
    "",
    'M.config = { greet = "Hello" }',
    "",
    "---@param opts? table",
    "---@return table",
    "function M.setup(opts)",
    '  M.config = vim.tbl_deep_extend("force", M.config, opts or {})',
    "  return M",
    "end",
    "",
    "---@param name? string",
    "---@return string",
    "function M.greet(name)",
    '  return ("%s, %s!"):format(M.config.greet, name or "world")',
    "end",
    "",
    "return M",
    "",
  }, "\n")
end

--- "nvim-plug" -> "NvimPlug" (usable as a :Command name)
local function pascal(ctx)
  local parts = {}
  for part in ctx.project_slug:gmatch("[%%w]+") do
    parts[#parts + 1] = part:sub(1, 1):upper() .. part:sub(2)
  end
  return table.concat(parts)
end

local function nvim_plugin_entry(ctx)
  local cmd = pascal(ctx) .. "Hello"
  return table.concat({
    ("-- %s entry point: user commands only."):format(ctx.project_name),
    "",
    ('if vim.g.loaded_%s then'):format(ctx.project_module),
    "  return",
    "end",
    ('vim.g.loaded_%s = 1'):format(ctx.project_module),
    "",
    ('vim.api.nvim_create_user_command("%s", function(args)'):format(cmd),
    ('  local ok, mod = pcall(require, "%s")'):format(ctx.project_module),
    "  if not ok then",
    '    vim.notify("' .. ctx.project_slug .. ' failed to load: " .. tostring(mod), vim.log.levels.ERROR)',
    "    return",
    "  end",
    '  vim.notify(mod.greet(args.args ~= "" and args.args or nil))',
    'end, { nargs = "?", desc = "' .. ctx.project_name .. ': greet" })',
    "",
  }, "\n")
end

local function nvim_doc(ctx)
  return table.concat({
    ("*%s.txt*  %s"):format(ctx.project_slug, ctx.project_name),
    "",
    "==============================================================================",
    "CONTENTS                                            *" .. ctx.project_slug .. "-contents*",
    "",
    "  1. Setup ................................ |" .. ctx.project_slug .. "-setup|",
    "  2. Commands ............................. |" .. ctx.project_slug .. "-commands|",
    "",
    "==============================================================================",
    "1. SETUP                                            *" .. ctx.project_slug .. "-setup*",
    "",
    ">lua",
    ('  require("%s").setup({})'):format(ctx.project_module),
    "<",
    "",
    "==============================================================================",
    "2. COMMANDS                                      *" .. ctx.project_slug .. "-commands*",
    "",
    (":%sHello [{name}]"):format(pascal(ctx)),
    "    Print a greeting.",
    "",
    "vim:tw=78:ts=8:ft=help:norl:",
    "",
  }, "\n")
end

local function nvim_tests(ctx)
  return table.concat({
    "-- nvim --headless --clean -u NONE -l tests/run.lua",
    "local root = vim.fn.getcwd()",
    "vim.opt.runtimepath:prepend(root)",
    "package.path = table.concat({",
    '  root .. "/lua/?.lua",',
    '  root .. "/lua/?/init.lua",',
    "  package.path,",
    '}, ";")',
    "",
    ("local plugin = require(\"%s\")"):format(ctx.project_module),
    "",
    "local failures, count = 0, 0",
    "",
    "local function test(name, fn)",
    "  count = count + 1",
    "  local ok, err = pcall(fn)",
    "  if ok then",
    '    print("ok   " .. name)',
    "  else",
    "    failures = failures + 1",
    '    print("FAIL " .. name .. ": " .. tostring(err))',
    "  end",
    "end",
    "",
    "local function eq(actual, expected)",
    "  if actual ~= expected then",
    "    error(('Expected %q, got %q'):format(expected, actual), 2)",
    "  end",
    "end",
    "",
    'test("greet defaults to world", function()',
    '  eq(plugin.greet(), "Hello, world!")',
    "end)",
    "",
    'test("setup() changes the greeting", function()',
    '  plugin.setup({ greet = "Hi" })',
    '  eq(plugin.greet("scaffold"), "Hi, scaffold!")',
    "end)",
    "",
    "print(('%d/%d passed'):format(count - failures, count))",
    "if failures > 0 then",
    '  vim.cmd("cq")',
    "end",
    'vim.cmd("qa!")',
    "",
  }, "\n")
end

