-- raylib templates (C++ and C).

local editor = require("scaffold.templates.editor")
local standards = require("scaffold.templates.standards")

local function cmake_lists(ctx)
  if ctx.language == "c" then
    return table.concat({
      "cmake_minimum_required(VERSION 3.20)",
      ("project(%s VERSION 0.1.0 LANGUAGES C)"):format(ctx.project_slug),
      "",
      ("set(CMAKE_C_STANDARD %s)"):format(ctx.standard or "17"),
      "set(CMAKE_C_STANDARD_REQUIRED ON)",
      "set(CMAKE_C_EXTENSIONS OFF)",
      "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)",
      "",
      "find_package(raylib REQUIRED)",
      "",
      ("add_executable(%s src/main.c)"):format(ctx.project_slug),
      ("target_link_libraries(%s PRIVATE raylib)"):format(ctx.project_slug),
      "",
    }, "\n")
  end

  return table.concat({
    "cmake_minimum_required(VERSION 3.20)",
    ("project(%s VERSION 0.1.0 LANGUAGES CXX)"):format(ctx.project_slug),
    "",
    ("set(CMAKE_CXX_STANDARD %s)"):format(ctx.standard or "20"),
    "set(CMAKE_CXX_STANDARD_REQUIRED ON)",
    "set(CMAKE_CXX_EXTENSIONS OFF)",
    "set(CMAKE_EXPORT_COMPILE_COMMANDS ON)",
    "",
    "find_package(raylib REQUIRED)",
    "",
    ("add_executable(%s src/main.cpp)"):format(ctx.project_slug),
    ("target_link_libraries(%s PRIVATE raylib)"):format(ctx.project_slug),
    "",
  }, "\n")
end

local function main_source(ctx)
  if ctx.language == "c" then
    return table.concat({
      '#include "raylib.h"',
      "",
      "int main(void) {",
      "    const int screen_width = 800;",
      "    const int screen_height = 450;",
      "",
      ('    InitWindow(screen_width, screen_height, "%s");'):format(ctx.project_name),
      "    SetTargetFPS(60);",
      "",
      "    while (!WindowShouldClose()) {",
      "        BeginDrawing();",
      "        ClearBackground(RAYWHITE);",
      '        DrawText("Hello from raylib (C)", 190, 200, 20, LIGHTGRAY);',
      '        DrawFPS(10, 10);',
      "        EndDrawing();",
      "    }",
      "",
      "    CloseWindow();",
      "    return 0;",
      "}",
      "",
    }, "\n")
  end
  return table.concat({
    '#include "raylib.h"',
    "",
    "#include <string>",
    "",
    "int main() {",
    "    constexpr int screen_width = 800;",
    "    constexpr int screen_height = 450;",
    "",
    ('    InitWindow(screen_width, screen_height, "%s");'):format(ctx.project_name),
    "    SetTargetFPS(60);",
    "",
    '    std::string title = "Hello from raylib (C++)";',
    "",
    "    while (!WindowShouldClose()) {",
    "        BeginDrawing();",
    "        ClearBackground(RAYWHITE);",
    "        DrawText(title.c_str(), 190, 200, 20, LIGHTGRAY);",
    "        DrawFPS(10, 10);",
    "        EndDrawing();",
    "    }",
    "",
    "    CloseWindow();",
    "    return 0;",
    "}",
    "",
  }, "\n")
end

local function readme(ctx)
  return table.concat({
    "# {{project_name}}",
    "",
    ("%s raylib project generated by Scaffold.nvim (%s, CMake)."):format(
      ctx.language == "c" and "C" or "C++",
      ctx.language == "c" and ("C" .. (ctx.standard or "17")) or ("C++" .. (ctx.standard or "20"))
    ),
    "",
    "## Requirements",
    "",
    "- raylib development package",
    "- CMake 3.20+",
    "",
    "Arch Linux: `sudo pacman -S raylib cmake`",
    "Debian/Ubuntu: `sudo apt install libraylib-dev cmake`",
    "",
    "## Build and run",
    "",
    "```sh",
    "cmake -S . -B build",
    "cmake --build build",
    ("./build/%s"):format(ctx.project_slug),
    "```",
    "",
  }, "\n")
end

local function gitignore()
  return table.concat({ "/build/", "*.o", "compile_commands.json", "" }, "\n")
end

return {
  templates = {
    {
      id = "cpp-raylib",
      name = "C++ raylib Game",
      language = "cpp",
      version = 1,
      description = "A raylib window with a game loop, built with CMake.",
      validate_options = standards.check,
      build_systems = { "cmake" },
      runtime_options = { "g++", "clang++" },
      default_runtime = "g++",
      default_build_system = "cmake",
      requires = { "cmake" },
      options = {
        standard = {
          type = "select",
          label = "C++ standard",
          values = { "17", "20", "23", "26" },
          default = "20",
        },
      },
      files = {
        ["CMakeLists.txt"] = cmake_lists,
        ["src/main.cpp"] = main_source,
        ["compile_flags.txt"] = function(ctx)
          return editor.compile_flags("c++" .. (ctx.standard or "20"))
        end,
        [".clangd"] = function(ctx)
          return editor.clangd("c++" .. (ctx.standard or "20"))
        end,
        [".gitignore"] = gitignore,
        ["README.md"] = readme,
      },
      commands = {
        configure = { "cmake", "-S", ".", "-B", "build", "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON" },
        build = { "cmake", "--build", "build" },
        run = function(ctx)
          return { "./build/" .. ctx.project_slug }
        end,
        clean = { "cmake", "--build", "build", "--target", "clean" },
      },
      install_commands = {},
    },
    {
      id = "c-raylib",
      name = "C raylib Game",
      language = "c",
      version = 1,
      description = "A raylib window with a game loop in C, built with CMake.",
      validate_options = standards.check,
      build_systems = { "cmake" },
      runtime_options = { "gcc", "clang" },
      default_runtime = "gcc",
      default_build_system = "cmake",
      requires = { "cmake" },
      options = {
        standard = {
          type = "select",
          label = "C standard",
          values = { "11", "17", "23" },
          default = "17",
        },
      },
      files = {
        ["CMakeLists.txt"] = cmake_lists,
        ["src/main.c"] = main_source,
        ["compile_flags.txt"] = function(ctx)
          return editor.compile_flags("c" .. (ctx.standard or "17"))
        end,
        [".clangd"] = function(ctx)
          return editor.clangd("c" .. (ctx.standard or "17"), "c-header")
        end,
        [".gitignore"] = gitignore,
        ["README.md"] = readme,
      },
      commands = {
        configure = { "cmake", "-S", ".", "-B", "build", "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON" },
        build = { "cmake", "--build", "build" },
        run = function(ctx)
          return { "./build/" .. ctx.project_slug }
        end,
        clean = { "cmake", "--build", "build", "--target", "clean" },
      },
      install_commands = {},
    },
  },
}
