-- JavaScript project templates.

local function install_argv(pm)
  if pm == "yarn" then
    return { "yarn" }
  end
  if pm == "bun" then
    return { "bun", "install" }
  end
  return { pm, "install" }
end

local function run_argv(pm, script)
  if pm == "yarn" then
    return { "yarn", script }
  end
  return { pm, "run", script }
end

local function test_argv(pm)
  if pm == "bun" then
    return { "bun", "test" }
  end
  return { pm, "test" }
end

